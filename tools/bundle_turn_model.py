#!/usr/bin/env python3
"""Write extension/lib/turn_model_data.js from plugin/scripts/raindragon_eta/turn_model.json,
so the extension ships the same numbers-only model as the plugin without fetching
anything. tests/turn_model.test.js fails if the two drift. Rerun after retraining."""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "plugin", "scripts", "raindragon_eta", "turn_model.json")
OUT = os.path.join(HERE, "..", "extension", "lib", "turn_model_data.js")


def main():
    with open(SRC) as f:
        model = json.load(f)
    body = json.dumps(model, separators=(",", ":"), allow_nan=False)
    with open(OUT, "w") as f:
        f.write("/* Generated by tools/bundle_turn_model.py from plugin/scripts/raindragon_eta/turn_model.json."
                " Numbers only. Do not edit. */\n"
                "(function (root) { root.RDTurnModelData = " + body + "; })"
                "(typeof self !== \"undefined\" ? self : this);\n")
    print("wrote", OUT, os.path.getsize(OUT))


if __name__ == "__main__":
    main()
